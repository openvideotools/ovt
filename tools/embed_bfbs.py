"""Embed binary FlatBuffers schemas (.bfbs) as C++ byte arrays (chapter 06 WI-0.083).

    embed_bfbs.py --out FILE.inc BFBS [BFBS ...]

For every input `<stem>.bfbs` the output defines, inside an anonymous namespace,

    alignas(8) constexpr std::uint8_t k_<stem>_bfbs[] = { 0x.., ... };

and the macro `OVT_BFBS_HAVE_<STEM>` (stem upper-cased), so the including source can tell which schemas
were embedded. The output is an include fragment for core/src/model/bfbs_resources.cpp; it is written
below the build tree's generated-code root (chapter 13 §13.2.3), never into the source tree. It is
byte-identical for byte-identical inputs (no timestamps, no paths), and it is only rewritten when its
content changes, so an unchanged schema does not recompile the resources. Exit 0 on success, 2 on a
usage or read error. Run with `python -I`; standard library only.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

BYTES_PER_LINE = 16
_STEM = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")


def array_name(stem: str) -> str:
    return f"k_{stem}_bfbs"


def render(inputs: list[tuple[str, bytes]]) -> str:
    """The include fragment for (stem, bytes) pairs, in the given order."""
    out = [
        "// Generated by tools/embed_bfbs.py (WI-0.083). Do not edit; do not commit.",
        "// clang-format off",
        "// NOLINTBEGIN",
        "namespace {",
    ]
    for stem, data in inputs:
        out.append("")
        out.append(f"#define OVT_BFBS_HAVE_{stem.upper()} 1")
        out.append(f"alignas(8) constexpr std::uint8_t {array_name(stem)}[] = {{")
        for i in range(0, len(data), BYTES_PER_LINE):
            chunk = data[i : i + BYTES_PER_LINE]
            out.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
        out.append("};")
    out += ["", "}  // namespace", "// NOLINTEND", "// clang-format on", ""]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, required=True, help="output include fragment")
    parser.add_argument("bfbs", type=Path, nargs="+", help="<stem>.bfbs files")
    args = parser.parse_args(argv)

    inputs: list[tuple[str, bytes]] = []
    for path in args.bfbs:
        stem = path.stem
        if path.suffix != ".bfbs" or not _STEM.fullmatch(stem):
            print(f"embed_bfbs: {path}: expected <identifier>.bfbs", file=sys.stderr)
            return 2
        if any(stem == s for s, _ in inputs):
            print(f"embed_bfbs: {path}: stem '{stem}' given twice", file=sys.stderr)
            return 2
        try:
            data = path.read_bytes()
        except OSError as exc:
            print(f"embed_bfbs: cannot read {path}: {exc}", file=sys.stderr)
            return 2
        if not data:
            print(f"embed_bfbs: {path} is empty", file=sys.stderr)
            return 2
        inputs.append((stem, data))

    text = render(inputs)
    try:
        if args.out.exists() and args.out.read_text(encoding="utf-8") == text:
            return 0
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text, encoding="utf-8", newline="\n")
    except OSError as exc:
        print(f"embed_bfbs: cannot write {args.out}: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
