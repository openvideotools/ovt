"""Generate the heatmap colour LUTs render/luts/*.h (chapter 10 §10.5.1, WI-2.431).

    gen_luts.py [-o render/luts]
    gen_luts.py --check [-o render/luts]

Each LUT is 256 RGBA8 entries (sRGB-encoded bytes, alpha 255), index 0 = minimum, written as
`inline constexpr std::array<uint8_t, 1024> ovt::render::luts::k<Name>` in render/luts/<name>.h. Entry i is the
colour map evaluated at x = i / 255, each channel rounded half away from zero to 0..255.

Sources (§10.5.1):
- viridis: the 256-entry table by Smith, van der Walt and Firing, released CC0 in github.com/BIDS/colormap (read
  from matplotlib's `_cm_listed.py`, which carries the same data).
- jet, hot: written here from their plain piecewise-linear definitions (no third-party data):
  jet  r = clamp(1.5 - |4x - 3|), g = clamp(1.5 - |4x - 2|), b = clamp(1.5 - |4x - 1|);
  hot  r = clamp(8x / 3), g = clamp(8x / 3 - 1), b = clamp(4x - 3).
- cividis is not generated yet: its data (pnnl/cmaputil) has a licence the policy does not list (spec question
  #471); Lut::Cividis falls back to viridis until then.
- turbo: Google's polynomial approximation of Turbo (Apache-2.0,
  https://gist.github.com/mikhailov-work/0d177465a8151eb6ede1768d51d476c7), coefficients below.

matplotlib is needed only to regenerate (pip install matplotlib); the output is checked in. --check exits 1 when a
checked-in header differs from what this script generates, 2 when matplotlib is missing.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

# Turbo polynomial approximation: rgb(x) = k4 . (1, x, x^2, x^3) + k2 . (x^4, x^5), clamped to [0, 1].
TURBO_K4 = (
    (0.13572138, 4.61539260, -42.66032258, 132.13108234),
    (0.09140261, 2.19418839, 4.84296658, -14.18503333),
    (0.10667330, 12.64194608, -60.58204836, 110.36276771),
)
TURBO_K2 = ((-152.94239396, 59.28637943), (4.27729857, 2.82956604), (-89.90310912, 27.34824973))


DEFAULT_COPYRIGHT = "2026 The Open Video Tools contributors"
# Headers whose colour data carries its upstream licence (tools/license_policy.toml [directories] lists each file).
# viridis: github.com/BIDS/colormap LICENSE.txt (CC0); turbo: the Google gist (Apache-2.0). jet and hot are our own.
LICENCES = {
    "viridis": ("2015 Nathaniel J. Smith, Stefan van der Walt, Eric Firing", "CC0-1.0"),
    "turbo": ("2019 Google LLC", "Apache-2.0"),
}


def to_byte(v: float) -> int:
    v = min(max(v, 0.0), 1.0)
    return int(v * 255.0 + 0.5)


def turbo(x: float) -> tuple[float, float, float]:
    x = min(max(x, 0.0), 1.0)
    v4 = (1.0, x, x * x, x * x * x)
    v2 = (v4[2] * v4[2], v4[3] * v4[2])
    return tuple(  # type: ignore[return-value]
        sum(k * v for k, v in zip(TURBO_K4[c], v4)) + sum(k * v for k, v in zip(TURBO_K2[c], v2)) for c in range(3)
    )


def jet(x: float) -> tuple[float, float, float]:
    return (1.5 - abs(4.0 * x - 3.0), 1.5 - abs(4.0 * x - 2.0), 1.5 - abs(4.0 * x - 1.0))


def hot(x: float) -> tuple[float, float, float]:
    return (8.0 * x / 3.0, 8.0 * x / 3.0 - 1.0, 4.0 * x - 3.0)


def tables() -> dict[str, list[tuple[int, int, int]]]:
    try:
        from matplotlib import _cm_listed  # only needed to regenerate (viridis)
    except ImportError:
        print("gen_luts.py: matplotlib is required (pip install matplotlib)", file=sys.stderr)
        sys.exit(2)
    out: dict[str, list[tuple[int, int, int]]] = {}
    data = _cm_listed._viridis_data
    assert len(data) == 256
    out["viridis"] = [(to_byte(r), to_byte(g), to_byte(b)) for r, g, b in data]
    out["jet"] = [tuple(to_byte(c) for c in jet(i / 255.0)) for i in range(256)]  # type: ignore[misc]
    out["hot"] = [tuple(to_byte(c) for c in hot(i / 255.0)) for i in range(256)]  # type: ignore[misc]
    out["turbo"] = [tuple(to_byte(c) for c in turbo(i / 255.0)) for i in range(256)]  # type: ignore[misc]
    return out


def header(name: str, rgb: list[tuple[int, int, int]]) -> str:
    sym = "k" + name.capitalize()
    guard = f"OVT_RENDER_LUTS_{name.upper()}_H"
    rows = []
    for i in range(0, 256, 4):
        rows.append("    " + " ".join(f"{r}, {g}, {b}, 255," for r, g, b in rgb[i : i + 4]))
    body = "\n".join(rows)
    copyright_line, spdx = LICENCES.get(name, (DEFAULT_COPYRIGHT, "LGPL-2.1-or-later"))
    return (
        f"// SPDX-FileCopyrightText: {copyright_line}\n"
        f"// SPDX-License-Identifier: {spdx}\n"
        "//\n"
        f"// {name} heatmap LUT (chapter 10 §10.5.1): 256 RGBA8 entries, sRGB-encoded, index 0 = minimum.\n"
        "// Generated by tools/gen_luts.py (sources and licences of the colour data are listed there); do not edit.\n"
        "\n"
        f"#ifndef {guard}\n#define {guard}\n\n#include <array>\n#include <cstdint>\n\n"
        "namespace ovt::render::luts {\n\n"
        "// clang-format off\n"
        f"inline constexpr std::array<uint8_t, 1024> {sym} = {{\n{body}\n}};\n"
        "// clang-format on\n\n"
        "}  // namespace ovt::render::luts\n\n"
        f"#endif  // {guard}\n"
    )


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("-o", "--out-dir", type=Path, default=Path(__file__).resolve().parent.parent / "render" / "luts")
    ap.add_argument("--check", action="store_true", help="compare with the checked-in headers instead of writing")
    args = ap.parse_args(argv)
    stale = []
    for name, rgb in tables().items():
        path = args.out_dir / f"{name}.h"
        text = header(name, rgb)
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path))
        else:
            args.out_dir.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    for p in stale:
        print(f"gen_luts.py: {p} is out of date", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
