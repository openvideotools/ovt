std::span<const PsshSystem> pssh_systems() noexcept {
  return kPsshSystems;
}

std::string_view pssh_system_name(std::span<const uint8_t, 16> system_id) noexcept {
  for (const PsshSystem& s : kPsshSystems) {
    if (std::equal(s.id.begin(), s.id.end(), system_id.begin())) {
      return s.name;
    }
  }
  return {};
}

std::string uuid_text(std::span<const uint8_t, 16> bytes) {
  constexpr std::string_view digits = "0123456789abcdef";
  std::string s;
  s.reserve(36);
  for (size_t i = 0; i < bytes.size(); ++i) {
    if (i == 4 || i == 6 || i == 8 || i == 10) {
      s += '-';
    }
    s += digits[bytes[i] >> 4U];
    s += digits[bytes[i] & 0xFU];
  }
  return s;
}

