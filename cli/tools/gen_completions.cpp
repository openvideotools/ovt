// Build-time generator of the ovt shell completion scripts (chapter 12 §12.2.15, WI-1.500 step 7). CLI11
// has no completion generator, so this walks the CLI::App tree of ovt_cli_lib (subcommands, options,
// IsMember choices, alias flags) and writes, into the directory given as argv[1]:
//   ovt.bash, ovt.zsh, ovt.fish       the scripts (installed by packaging, chapter 13 §13.6)
//   completions_data.cpp              the same bytes as char arrays, compiled into the ovt binary
// Output is a pure function of the CLI tree, so it is byte-identical between runs (§0.7.5).
//
// Usage: gen_completions <output-dir> [<cli-name>]

#include <fmt/format.h>

#include <cstdio>
#include <span>
#include <string>
#include <string_view>
#include <vector>

#include "app.h"

namespace {

struct Opt {
  std::vector<std::string> longs;
  std::vector<std::string> shorts;
  bool takes_value = false;
  std::vector<std::string> choices;
  std::string help;
};

struct Cmd {
  std::string name;
  std::string help;
  std::vector<Opt> opts;
  std::vector<std::string> positional_choices;  // choices of the first positional
};

std::vector<Opt> options_of(const ovt::cli::Cli& cli, const CLI::App& app, std::vector<std::string>* positional) {
  std::vector<Opt> out;
  for (const CLI::Option* o : app.get_options()) {
    const auto* ch = cli.choices(o);
    if (o->get_positional() && !o->nonpositional()) {
      if (positional != nullptr && positional->empty() && ch != nullptr) {
        *positional = *ch;
      }
      continue;
    }
    out.push_back(Opt{o->get_lnames(), o->get_snames(), o->get_expected_max() > 0,
                      ch != nullptr ? *ch : std::vector<std::string>{}, o->get_description()});
  }
  return out;
}

std::string join(const std::vector<std::string>& v, std::string_view sep, std::string_view prefix = "") {
  std::string s;
  for (const std::string& x : v) {
    s += (s.empty() ? "" : std::string(sep)) + std::string(prefix) + x;
  }
  return s;
}

std::vector<std::string> spellings(const Opt& o) {
  std::vector<std::string> v;
  v.reserve(o.shorts.size() + o.longs.size());
  for (const auto& s : o.shorts) {
    v.push_back("-" + s);
  }
  for (const auto& l : o.longs) {
    v.push_back("--" + l);
  }
  return v;
}

std::string escape(std::string_view s, std::string_view specials) {
  std::string out;
  for (const char c : s) {
    if (c == '\'') {
      out += "'\\''";
      continue;
    }
    if (specials.find(c) != std::string_view::npos) {
      out.push_back('\\');
    }
    out.push_back(c);
  }
  return out;
}

std::string bash(const std::string& name, const std::vector<Opt>& globals, const std::vector<Cmd>& cmds) {
  std::string value_cases;
  std::vector<std::string> global_words;
  std::vector<std::string> cmd_names;
  for (const Opt& o : globals) {
    const auto sp = spellings(o);
    global_words.insert(global_words.end(), sp.begin(), sp.end());
  }
  std::string cmd_cases;
  for (const Cmd& c : cmds) {
    cmd_names.push_back(c.name);
    std::vector<std::string> words = global_words;
    for (const Opt& o : c.opts) {
      const auto sp = spellings(o);
      words.insert(words.end(), sp.begin(), sp.end());
    }
    cmd_cases += fmt::format(
        "    {})\n      if [[ \"$cur\" == -* ]]; then COMPREPLY=($(compgen -W \"{}\" -- \"$cur\"))\n"
        "      else COMPREPLY=($(compgen -W \"{}\" -- \"$cur\")); fi ;;\n",
        c.name, join(words, " "), join(c.positional_choices, " "));
  }
  std::vector<Opt> all = globals;
  for (const Cmd& c : cmds) {
    all.insert(all.end(), c.opts.begin(), c.opts.end());
  }
  for (const Opt& o : all) {
    if (!o.takes_value) {
      continue;
    }
    value_cases += o.choices.empty() ? fmt::format("    {}) COMPREPLY=($(compgen -f -- \"$cur\")); return ;;\n",
                                                   join(spellings(o), "|"))
                                     : fmt::format("    {}) COMPREPLY=($(compgen -W \"{}\" -- \"$cur\")); return ;;\n",
                                                   join(spellings(o), "|"), join(o.choices, " "));
  }
  return fmt::format(
      "# bash completion for {0} (generated by cli/tools/gen_completions.cpp; do not edit)\n"
      "_{0}() {{\n"
      "  local cur=\"${{COMP_WORDS[COMP_CWORD]}}\" prev=\"${{COMP_WORDS[COMP_CWORD-1]}}\" sub=\"\" i\n"
      "  for ((i = 1; i < COMP_CWORD; i++)); do\n"
      "    case \"${{COMP_WORDS[i]}}\" in {1}) sub=\"${{COMP_WORDS[i]}}\"; break ;; esac\n"
      "  done\n"
      "  case \"$prev\" in\n{2}  esac\n"
      "  case \"$sub\" in\n{3}"
      "    *)\n      if [[ \"$cur\" == -* ]]; then COMPREPLY=($(compgen -W \"{4}\" -- \"$cur\"))\n"
      "      else COMPREPLY=($(compgen -W \"{5}\" -- \"$cur\")); fi ;;\n"
      "  esac\n"
      "}}\n"
      "complete -F _{0} {0}\n",
      name, join(cmd_names, "|"), value_cases, cmd_cases, join(global_words, " "), join(cmd_names, " "));
}

std::string zsh_spec(const Opt& o) {
  const auto sp = spellings(o);
  std::string action;
  if (o.takes_value) {
    action = o.choices.empty() ? ":value:_files" : fmt::format(":value:({})", join(o.choices, " "));
  }
  const std::string names = sp.size() == 1 ? sp[0] : fmt::format("{{{}}}", join(sp, ","));
  const std::string excl = sp.size() == 1 ? "" : fmt::format("'({})'", join(sp, " "));
  return fmt::format("{}{}'[{}]{}'", excl, names, escape(o.help, "[]:"), action);
}

std::string zsh(const std::string& name, const std::vector<Opt>& globals, const std::vector<Cmd>& cmds) {
  std::string global_specs;
  for (const Opt& o : globals) {
    global_specs += "    " + zsh_spec(o) + "\n";
  }
  std::string cmd_list;
  std::string cmd_cases;
  for (const Cmd& c : cmds) {
    cmd_list += fmt::format("    '{}:{}'\n", c.name, escape(c.help, ":"));
    std::string specs;
    for (const Opt& o : c.opts) {
      specs += " " + zsh_spec(o);
    }
    cmd_cases += fmt::format("        {}) _arguments -s $globals{} '1:value:({})' ;;\n", c.name, specs,
                             join(c.positional_choices, " "));
  }
  return fmt::format(
      "#compdef {0}\n"
      "# zsh completion for {0} (generated by cli/tools/gen_completions.cpp; do not edit)\n"
      "_{0}() {{\n"
      "  local -a globals cmds\n"
      "  local state line\n"
      "  globals=(\n{1}  )\n"
      "  cmds=(\n{2}  )\n"
      "  _arguments -s -C $globals '1: :->cmd' '*:: :->args'\n"
      "  case $state in\n"
      "    cmd) _describe command cmds ;;\n"
      "    args)\n      case $line[1] in\n{3}      esac ;;\n"
      "  esac\n"
      "}}\n"
      "if [ \"$funcstack[1]\" = \"_{0}\" ]; then _{0} \"$@\"; else compdef _{0} {0}; fi\n",
      name, global_specs, cmd_list, cmd_cases);
}

std::string fish_lines(const std::string& name, const std::vector<Opt>& opts, const std::string& condition) {
  std::string out;
  for (const Opt& o : opts) {
    std::string line = "complete -c ";
    line += name;
    line += condition;
    for (const auto& s : o.shorts) {
      line += " -s " + s;
    }
    for (const auto& l : o.longs) {
      line += " -l " + l;
    }
    if (o.takes_value) {
      line += o.choices.empty() ? " -r -F" : fmt::format(" -x -a '{}'", join(o.choices, " "));
    }
    out += line + fmt::format(" -d '{}'\n", escape(o.help, ""));
  }
  return out;
}

std::string fish(const std::string& name, const std::vector<Opt>& globals, const std::vector<Cmd>& cmds) {
  std::string out = fmt::format(
      "# fish completion for {0} (generated by cli/tools/gen_completions.cpp; do not edit)\ncomplete -c {0} -f\n",
      name);
  for (const Cmd& c : cmds) {
    out += fmt::format("complete -c {} -n __fish_use_subcommand -a {} -d '{}'\n", name, c.name, escape(c.help, ""));
  }
  out += fish_lines(name, globals, "");
  for (const Cmd& c : cmds) {
    const std::string cond = fmt::format(" -n '__fish_seen_subcommand_from {}'", c.name);
    out += fish_lines(name, c.opts, cond);
    if (!c.positional_choices.empty()) {
      out += fmt::format("complete -c {}{} -x -a '{}'\n", name, cond, join(c.positional_choices, " "));
    }
  }
  return out;
}

bool write_file(const std::string& path, std::string_view text) {
  std::FILE* f = std::fopen(path.c_str(), "wb");
  if (f == nullptr) {
    return false;
  }
  const bool ok = std::fwrite(text.data(), 1, text.size(), f) == text.size();
  return std::fclose(f) == 0 && ok;
}

std::string as_array(std::string_view id, std::string_view text) {
  std::string out = fmt::format("constexpr unsigned char {}[] = {{", id);
  for (std::size_t i = 0; i < text.size(); ++i) {
    out += fmt::format("{}{}", i % 16 == 0 ? "\n    " : " ", static_cast<int>(static_cast<unsigned char>(text[i])));
    out += ",";
  }
  return out + "\n    0};\n";
}

}  // namespace

int main(int argc, char** argv) {
  const std::span<char*> args(argv, static_cast<std::size_t>(argc));
  if (args.size() < 2) {
    static_cast<void>(std::fputs("usage: gen_completions <output-dir> [<cli-name>]\n", stderr));
    return 2;
  }
  const std::string dir = args[1];
  const std::string name = args.size() > 2 ? args[2] : "ovt";
  const ovt::cli::Cli cli;
  CLI::App& app = const_cast<ovt::cli::Cli&>(cli).app();  // NOLINT(cppcoreguidelines-pro-type-const-cast)
  const std::vector<Opt> globals = options_of(cli, app, nullptr);
  std::vector<Cmd> cmds;
  for (const CLI::App* sub : app.get_subcommands({})) {
    Cmd c{sub->get_name(), sub->get_description(), {}, {}};
    c.opts = options_of(cli, *sub, &c.positional_choices);
    std::erase_if(c.opts, [](const Opt& o) { return !o.longs.empty() && o.longs.front() == "help"; });
    cmds.push_back(std::move(c));
  }
  const std::string b = bash(name, globals, cmds);
  const std::string z = zsh(name, globals, cmds);
  const std::string f = fish(name, globals, cmds);
  const std::string data = fmt::format(
      "// Generated by cli/tools/gen_completions.cpp; do not edit.\n"
      "// NOLINTBEGIN\n#include \"completions.h\"\n\nnamespace {{\n{}{}{}"
      "std::string_view as_view(const unsigned char* p, std::size_t n) {{\n"
      "  return {{reinterpret_cast<const char*>(p), n}};\n}}\n}}  // namespace\n\n"
      "ovt::cli::CompletionScripts ovt::cli::embedded_completions() noexcept {{\n"
      "  return {{as_view(kBash, {}), as_view(kZsh, {}), as_view(kFish, {})}};\n}}\n// NOLINTEND\n",
      as_array("kBash", b), as_array("kZsh", z), as_array("kFish", f), b.size(), z.size(), f.size());
  const bool ok = write_file(dir + "/" + name + ".bash", b) && write_file(dir + "/" + name + ".zsh", z) &&
                  write_file(dir + "/" + name + ".fish", f) && write_file(dir + "/completions_data.cpp", data);
  if (!ok) {
    static_cast<void>(std::fprintf(stderr, "gen_completions: cannot write into %s\n", dir.c_str()));
    return 1;
  }
  return 0;
}
