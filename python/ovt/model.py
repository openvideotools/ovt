"""Read stored OVT FrameAnalysis records from Python without the C API (chapter 06 WI-0.095).

The FlatBuffers readers in ``ovt.fb`` are generated by ``flatc --python`` at build time and are packaged
into the wheel; they are never committed.  This module adds the helpers research scripts and test oracles
need on top of them:

* :func:`load_frame_analysis` reads a ``.fa`` / ``.fa.zst`` file (plain or size-prefixed, zstd or not).
* :func:`grid_as_numpy` returns the ``CellGrid`` vectors as ``(cells_h, cells_w)`` NumPy views (no copy).
* :func:`blocks_as_dataframe` returns the block tree as a pandas DataFrame (pandas is optional).
* :func:`mv_to_luma_samples` converts the 1/16 luma sample motion vector unit of the schema.
"""

from __future__ import annotations

import struct
from pathlib import Path
from typing import TYPE_CHECKING

import numpy as np

if TYPE_CHECKING:  # pragma: no cover
    from ovt.fb.FrameAnalysis import FrameAnalysis

__all__ = [
    "MV_UNITS_PER_LUMA_SAMPLE",
    "blocks_as_dataframe",
    "grid_as_numpy",
    "load_frame_analysis",
    "mv_to_luma_samples",
    "parse_frame_analysis",
]

#: FrameAnalysis file identifier ("OVTA"), chapter 06 §6.2.
FRAME_ANALYSIS_IDENTIFIER = b"OVTA"
#: Motion vectors are stored in 1/16 luma sample units (backbone §0.5.4).
MV_UNITS_PER_LUMA_SAMPLE = 16
_ZSTD_MAGIC = b"\x28\xb5\x2f\xfd"

# CellGrid vector name -> element dtype (little-endian, as FlatBuffers stores them). Names are the
# schema's field names; the dtypes follow core/schema/ovt_model.fbs `table CellGrid`.
_GRID_FIELDS: dict[str, str] = {
    "block_id": "u4",
    "partition_id": "u2",
    "pred": "u1",
    "qp": "i2",
    "intra_mode_y": "i2",
    "intra_mode_c": "i2",
    "mv0_x": "i2",
    "mv0_y": "i2",
    "mv1_x": "i2",
    "mv1_y": "i2",
    "ref0": "i1",
    "ref1": "i1",
    "tx_log2_w": "u1",
    "tx_log2_h": "u1",
    "tx_type": "u1",
    "cbf": "u1",
    "bits_x8": "u4",
    "deblock_bs_v": "u1",
    "deblock_bs_h": "u1",
    "filter_idx": "u1",
}


def _camel(name: str) -> str:
    """``mv0_x`` -> ``Mv0X`` (flatc's Python accessor naming)."""
    return "".join(part[:1].upper() + part[1:] for part in name.split("_"))


def _decompress(data: bytes) -> bytes:
    if data[:4] != _ZSTD_MAGIC:
        return data
    try:
        import zstandard
    except ImportError as exc:  # pragma: no cover - declared dependency
        raise ImportError("reading .fa.zst files needs the 'zstandard' package") from exc
    # Frames written by the C++ side carry the content size; fall back to streaming when they do not.
    with zstandard.ZstdDecompressor().stream_reader(data) as reader:
        return reader.read()


def parse_frame_analysis(data: bytes | bytearray | memoryview) -> FrameAnalysis:
    """Parse an in-memory FrameAnalysis buffer (plain or size-prefixed, identifier ``OVTA``).

    The returned object keeps ``data`` alive; NumPy views from :func:`grid_as_numpy` point into it.
    """
    from ovt.fb.FrameAnalysis import FrameAnalysis

    buf = data if isinstance(data, (bytes, bytearray)) else bytes(data)
    if len(buf) < 12:
        raise ValueError("buffer too short for a FrameAnalysis")
    (prefix,) = struct.unpack_from("<I", buf, 0)
    offset = 0
    if prefix == len(buf) - 4 and buf[8:12] == FRAME_ANALYSIS_IDENTIFIER:
        offset = 4  # size-prefixed (§6.7.1: every stored buffer is written with FinishSizePrefixed)
    if buf[offset + 4 : offset + 8] != FRAME_ANALYSIS_IDENTIFIER:
        raise ValueError("not a FrameAnalysis buffer (identifier OVTA missing)")
    return FrameAnalysis.GetRootAs(buf, offset)


def load_frame_analysis(path: str | Path) -> FrameAnalysis:
    """Read a stored ``FrameAnalysis`` from ``*.fa`` or ``*.fa.zst`` (size-prefix and zstd are detected)."""
    raw = Path(path).read_bytes()
    return parse_frame_analysis(_decompress(raw))


def grid_as_numpy(fa: FrameAnalysis) -> dict[str, np.ndarray]:
    """Return every ``CellGrid`` vector as an array of shape ``(cells_h, cells_w)``.

    Populated vectors are zero-copy, read-only views over the FlatBuffer (``*AsNumpy()`` accessors). A vector
    the plugin did not provide is empty in the schema; it comes back as an empty ``(0, 0)`` array of the right
    dtype (``*AsNumpy()`` itself returns ``0`` for those, §6 WI-0.095 pitfall).
    """
    grid = fa.Grid()
    if grid is None:
        raise ValueError("FrameAnalysis has no grid")
    w, h = int(grid.CellsW()), int(grid.CellsH())
    out: dict[str, np.ndarray] = {}
    for name, dtype in _GRID_FIELDS.items():
        accessor = _camel(name)
        if getattr(grid, accessor + "Length")() == 0:
            out[name] = np.empty((0, 0), dtype=np.dtype(dtype))
            continue
        arr = getattr(grid, accessor + "AsNumpy")()
        if arr.size != w * h:
            raise ValueError(f"grid.{name} has {arr.size} entries, expected {w}x{h}={w * h}")
        out[name] = arr.reshape(h, w)
    return out


def mv_to_luma_samples(v):
    """Convert motion vector component(s) from 1/16 luma sample units to luma samples (float)."""
    if isinstance(v, np.ndarray):
        return v.astype(np.float64) / MV_UNITS_PER_LUMA_SAMPLE
    return v / MV_UNITS_PER_LUMA_SAMPLE


def blocks_as_dataframe(fa: FrameAnalysis):
    """Return ``FrameAnalysis.blocks`` as a ``pandas.DataFrame`` (index = position in ``blocks[]``).

    Columns: ``id, parent, kind, x, y, w, h, level, partition_type, pred, skip, merge_or_direct, qp, bits_x8,
    ext_type``; ``kind`` and ``pred`` are the enum names. Needs pandas (optional dependency).
    """
    try:
        import pandas as pd
    except ImportError as exc:
        raise ImportError("blocks_as_dataframe needs the optional 'pandas' package") from exc
    from ovt.fb.BlockKind import BlockKind
    from ovt.fb.PredKind import PredKind

    def names(enum_cls) -> dict[int, str]:
        # flatc appends "_" to names that are Python keywords (`PredKind.None_`); the schema name has none.
        return {v: k.rstrip("_") for k, v in vars(enum_cls).items() if isinstance(v, int) and not k.startswith("_")}

    kinds, preds = names(BlockKind), names(PredKind)
    rows = []
    for i in range(fa.BlocksLength()):
        b = fa.Blocks(i)
        r = b.Rect()
        ext_type = b.ExtType()
        rows.append(
            {
                "id": b.Id(),
                "parent": b.Parent(),
                "kind": kinds.get(b.Kind(), str(b.Kind())),
                "x": r.X(),
                "y": r.Y(),
                "w": r.W(),
                "h": r.H(),
                "level": b.Level(),
                "partition_type": b.PartitionType(),
                "pred": preds.get(b.Pred(), str(b.Pred())),
                "skip": bool(b.Skip()),
                "merge_or_direct": bool(b.MergeOrDirect()),
                "qp": b.Qp(),
                "bits_x8": b.BitsX8(),
                "ext_type": ext_type.decode() if ext_type else "",
            }
        )
    return pd.DataFrame(rows)
