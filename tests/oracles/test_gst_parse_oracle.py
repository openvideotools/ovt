"""Acceptance tests of WI-0.562 (chapter 14 §14.4.2): run gst_parse_oracle on streams made with the §14.3.3 recipes.

    test_gst_parse_oracle.py <path to gst_parse_oracle>

The corpus files (syn_h264_multislice_cavlc.264, syn_av1_tiles_cdef_lr.ivf) are generated by WI-0.553; until they exist
the streams are encoded here from a lavfi test pattern with the same encoder options (SPEC-ASSUMPTION(#153): the
tests accept any stream with the recipe's properties, so the corpus files satisfy them unchanged). Set
OVT_GST_ORACLE_H264 / OVT_GST_ORACLE_AV1 to use the corpus files. Exit 77 (CTest skip) when ffmpeg or an encoder is
missing.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

SKIP = 77


def run(cmd: list[str], **kw) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, capture_output=True, text=True, check=False, **kw)  # noqa: S603


def encoders() -> str:
    ff = shutil.which("ffmpeg")
    if ff is None:
        return ""
    return run([ff, "-hide_banner", "-encoders"]).stdout


def oracle(exe: str, *args: str) -> tuple[int, list[dict]]:
    res = run([exe, *args])
    units = [json.loads(line) for line in res.stdout.splitlines()]
    return res.returncode, units


def encode(work: Path, size: str, frames: int, codec_args: list[str], out: str) -> Path:
    src = work / f"src_{size}.y4m"
    if not src.exists():
        r = run(["ffmpeg", "-v", "error", "-y", "-f", "lavfi", "-i", f"testsrc2=size={size}:rate=30",
                 "-frames:v", str(frames), "-pix_fmt", "yuv420p", str(src)])  # fmt: skip
        assert r.returncode == 0, r.stderr
    dst = work / out
    r = run(["ffmpeg", "-v", "error", "-y", "-i", str(src), *codec_args, str(dst)])
    assert r.returncode == 0, r.stderr
    return dst


def check_header_struct(units: list[dict]) -> None:
    """Every line is a header-struct document: objects of integers, arrays and objects, no parse errors."""
    for u in units:
        assert "error" not in u, u
        assert set(u["unit"]) == {"index", "offset", "type"}, u["unit"]
        for key, val in u.items():
            assert isinstance(val, dict), (key, val)


def test_h264_multislice(exe: str, work: Path, enc: str) -> None:
    given = os.environ.get("OVT_GST_ORACLE_H264")
    if given:
        path = Path(given)
    elif "libx264" in enc:
        path = encode(work, "320x240", 8, ["-c:v", "libx264", "-profile:v", "baseline", "-x264-params",
                                           "slices=4:cabac=0:keyint=15:scenecut=0", "-f", "h264"], "m.264")  # fmt: skip
    else:
        print("SKIP: libx264 missing")
        return
    rc, units = oracle(exe, "--codec", "h264", str(path))
    assert rc == 0
    check_header_struct(units)
    sps = [u for u in units if "sps" in u]
    assert sps and sps[0]["sps"]["profile_idc"] == 66 and sps[0]["sps"]["frame_mbs_only_flag"] == 1
    # Acceptance 1: 4 slice headers per frame with first_mb_in_slice increasing.
    frames: list[list[int]] = []
    for u in units:
        if "slice_header" in u:
            first = u["slice_header"]["first_mb_in_slice"]
            if first == 0:
                frames.append([])
            frames[-1].append(first)
    assert len(frames) >= 2
    for firsts in frames:
        assert len(firsts) == 4, firsts
        assert firsts == sorted(set(firsts)), firsts


def test_av1_tiles(exe: str, work: Path, enc: str) -> None:
    given = os.environ.get("OVT_GST_ORACLE_AV1")
    if given:
        path = Path(given)
    elif "libaom-av1" in enc:
        path = encode(work, "1280x720", 3, ["-c:v", "libaom-av1", "-cpu-used", "8", "-crf", "30", "-b:v", "0",
                                            "-tile-columns", "2", "-tile-rows", "1", "-enable-cdef", "1",
                                            "-enable-restoration", "1", "-lag-in-frames", "0"], "m.ivf")  # fmt: skip
    else:
        print("SKIP: libaom-av1 missing")
        return
    # Both spellings of the format flag, and sniffing, give the same output.
    outs = []
    for flags in (["--ivf"], []):
        rc, units = oracle(exe, "--codec", "av1", *flags, str(path))
        assert rc == 0
        outs.append(units)
    assert outs[0] == outs[1]
    units = outs[0]
    check_header_struct(units)
    # Acceptance 2: tile_cols == 4 (--tile-columns=2 is log2) and enable_cdef == 1.
    seq = [u["sequence_header"] for u in units if "sequence_header" in u]
    frames = [u["frame_header"] for u in units if "frame_header" in u]
    assert seq and seq[0]["enable_cdef"] == 1
    assert frames and all(f["tile_info"]["tile_cols"] == 4 for f in frames)
    tg = [u["tile_group"] for u in units if "tile_group" in u]
    assert tg and all(len(t["entry"]["tile_size"]) == t["num_tiles"] for t in tg)
    # The same stream as a bare OBU stream (ffmpeg's obu muxer) parses to the same headers.
    obu = work / "m.obu"
    r = run(
        [
            "ffmpeg",
            "-v",
            "error",
            "-y",
            "-i",
            str(path),
            "-c",
            "copy",
            "-f",
            "obu",
            str(obu),
        ]
    )
    if r.returncode == 0:
        rc, obu_units = oracle(exe, "--codec", "av1", "--obu", str(obu))
        assert rc == 0
        strip = [{k: v for k, v in u.items() if k != "unit"} for u in obu_units if "frame_header" in u]
        ivf = [{k: v for k, v in u.items() if k != "unit"} for u in units if "frame_header" in u]
        assert strip == ivf


def test_h265(exe: str, work: Path, enc: str) -> None:
    if "libx265" not in enc:
        print("SKIP: libx265 missing")
        return
    path = encode(work, "320x240", 8, ["-c:v", "libx265", "-x265-params", "keyint=15:no-open-gop=1:log-level=none",
                                       "-f", "hevc"], "m.265")  # fmt: skip
    rc, units = oracle(exe, "--codec", "h265", str(path))
    assert rc == 0
    check_header_struct(units)
    kinds = {k for u in units for k in u if k != "unit"}
    assert {"vps", "sps", "pps", "slice_header"} <= kinds
    sps = next(u["sps"] for u in units if "sps" in u)
    assert sps["profile_tier_level"]["profile_idc"] == 1 and sps["chroma_format_idc"] == 1
    slices = [u["slice_header"] for u in units if "slice_header" in u]
    assert slices[0]["first_slice_segment_in_pic_flag"] == 1


def test_errors(exe: str, work: Path) -> None:
    assert run([exe]).returncode == 2
    assert run([exe, "--codec", "h264", "--obu", "x"]).returncode == 2
    assert run([exe, "--codec", "h264", str(work / "missing")]).returncode == 3
    junk = work / "junk.264"
    junk.write_bytes(b"\x00\x00\x01\x67" + b"\xff" * 5)  # an SPS NAL unit that cannot be parsed
    rc, units = oracle(exe, "--codec", "h264", str(junk))
    assert rc == 1 and units and "error" in units[0]


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    exe = sys.argv[1]
    enc = encoders()
    if not enc and not (os.environ.get("OVT_GST_ORACLE_H264") and os.environ.get("OVT_GST_ORACLE_AV1")):
        print("SKIP: ffmpeg not found")
        return SKIP
    with tempfile.TemporaryDirectory(prefix="gst_oracle_") as tmp:
        work = Path(tmp)
        test_errors(exe, work)
        test_h264_multislice(exe, work, enc)
        test_av1_tiles(exe, work, enc)
        test_h265(exe, work, enc)
    print("gst_parse_oracle: all checks passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
